func openTableTemplate(t *testing.T, u *UI) {
	t.Helper()
	u.commandPalette()
	panel := u.dialogContent.(*tview.Flex)
	name := "New table template"
	if u.cfg.Language == "es" {
		name = "Nueva plantilla de tabla"
	}
	panel.GetItem(0).(*tview.InputField).SetText(name)
	list := panel.GetItem(1).(*tview.List)
	if list.GetItemCount() != 1 {
		t.Fatalf("table command missing: %d matches", list.GetItemCount())
	}
	list.GetItemSelectedFunc(0)()
}

func submitTableName(u *UI, name string) {
	f := currentForm(u)
	f.GetFormItem(0).(*tview.InputField).SetText(name)
	saveForm(u, f)
}

func TestTableTemplateCommandForEachEngine(t *testing.T) {
	for _, tc := range []struct{ engine, name, target, id, column string }{
		{"sqlserver", "orders]2026", "[dbo].[orders]]2026]", "INT IDENTITY(1,1)", "NVARCHAR(255)"},
		{"mysql", "orders`2026", "`inventory`.`orders``2026`", "INT AUTO_INCREMENT", "VARCHAR(255)"},
		{"postgres", "orders\"2026", "\"public\".\"orders\"\"2026\"", "INTEGER GENERATED BY DEFAULT AS IDENTITY", "VARCHAR(255)"},
	} {
		t.Run(tc.engine, func(t *testing.T) {
			u, _ := modeTestUI(t)
			tab := u.active()
			tab.Session = &db.Session{Adapter: db.NewAdapter(tc.engine)}
			tab.Profile.Engine = tc.engine
			tab.Profile.Database = "inventory"
			tab.Editor.SetText("SELECT 1;")
			tab.Saved = "SELECT 1;"
			tab.Path = "existing.sql"
			tab.Object = &db.Object{Schema: "dbo", Name: "existing", Kind: "table"}
			tab.Catalog = []db.Object{{Name: "existing", Kind: "table"}}
			session := tab.Session
			openTableTemplate(t, u)
			if got := currentForm(u).GetFormItem(0).(*tview.InputField).GetText(); got != "new_table" {
				t.Fatal("unexpected default", got)
			}
			submitTableName(u, tc.name)
			want := "CREATE TABLE " + tc.target + " (\n    id " + tc.id + " PRIMARY KEY,\n    name " + tc.column + " NOT NULL\n);"
			if got := tab.Editor.Area.GetText(); got != want {
				t.Fatalf("SQL=%q want=%q", got, want)
			}
			if tab.Path != "" || tab.Saved != "" || tab.Object != nil {
				t.Fatal("template retained old document identity")
			}
			if tab.Session != session || len(tab.Catalog) != 1 || tab.Catalog[0].Name != "existing" || len(tab.Results) != 0 {
				t.Fatal("template changed session or database results/catalog")
			}
			// Adapter-only session has no live database: template generation must not execute SQL.
		})
	}
}

func TestTableTemplatePreservesDirtySQLUntilConfirmed(t *testing.T) {
	for _, action := range []string{"cancel prompt", "empty", "blank", "cancel replacement", "confirm replacement"} {
		t.Run(action, func(t *testing.T) {
			u, _ := modeTestUI(t)
			tab := u.active()
			tab.Session = &db.Session{Adapter: db.NewAdapter("sqlserver")}
			tab.Profile.Engine = "sqlserver"
			tab.Editor.SetText("SELECT 'unsaved';")
			tab.Saved = "SELECT 1;"
			tab.Path = "existing.sql"
			obj := &db.Object{Name: "existing", Kind: "table"}
			tab.Object = obj
			openTableTemplate(t, u)
			switch action {
			case "cancel prompt":
				fileDialogKey(u, tcell.KeyEscape)
			case "empty":
				submitTableName(u, "")
			case "blank":
				submitTableName(u, "   ")
			default:
				submitTableName(u, "orders")
				if _, ok := u.dialogContent.(*tview.Modal); !ok {
					t.Fatal("dirty SQL replaced without confirmation")
				}
				if tab.Editor.Area.GetText() != "SELECT 'unsaved';" {
					t.Fatal("prompt already replaced dirty SQL")
				}
				if action == "confirm replacement" {
					fileDialogKey(u, tcell.KeyRight)
				}
				fileDialogKey(u, tcell.KeyEnter)
			}
			if action == "confirm replacement" {
				if !strings.HasPrefix(tab.Editor.Area.GetText(), "CREATE TABLE [dbo].[orders]") || tab.Path != "" || tab.Saved != "" || tab.Object != nil {
					t.Fatal("confirmed template not loaded")
				}
			} else if tab.Editor.Area.GetText() != "SELECT 'unsaved';" || tab.Path != "existing.sql" || tab.Saved != "SELECT 1;" || tab.Object != obj {
				t.Fatal("cancelled template changed document")
			}
		})
	}
}

func TestTableTemplateContextGuardsAndSpanish(t *testing.T) {
	for _, state := range []string{"disconnected", "choosing database", "mysql without database", "spanish"} {
		t.Run(state, func(t *testing.T) {
			u, _ := modeTestUI(t)
			tab := u.active()
			tab.Editor.SetText("SELECT 1;")
			tab.Saved = "SELECT 1;"
			if state != "disconnected" {
				tab.Session = &db.Session{Adapter: db.NewAdapter("mysql")}
				tab.Profile.Engine = "mysql"
			}
			if state == "choosing database" {
				tab.SelectingDatabase = true
			}
			if state == "spanish" {
				u.cfg.Language = "es"
				tab.Profile.Database = "inventory"
			}
			openTableTemplate(t, u)
			if state == "spanish" {
				f := currentForm(u)
				if !strings.Contains(f.GetTitle(), "Nombre de la tabla nueva") {
					t.Fatal("table prompt not translated", f.GetTitle())
				}
				submitTableName(u, "new_table")
				if !strings.HasPrefix(tab.Editor.Area.GetText(), "CREATE TABLE `inventory`.`new_table`") {
					t.Fatal("Spanish command failed")
				}
			} else {
				if _, ok := u.dialogContent.(*tview.Form); ok {
					t.Fatal("context guard allowed table prompt")
				}
				if tab.Editor.Area.GetText() != "SELECT 1;" || tab.Saved != "SELECT 1;" {
					t.Fatal("rejected command changed SQL")
				}
			}
		})
	}
}

func TestRoutineTemplateCommandStillWorks(t *testing.T) {
	u, _ := modeTestUI(t)
	tab := u.active()
	tab.Session = &db.Session{Adapter: db.NewAdapter("sqlserver")}
	tab.Profile.Engine = "sqlserver"
	u.commandPalette()
	panel := u.dialogContent.(*tview.Flex)
	panel.GetItem(0).(*tview.InputField).SetText("New routine template")
	list := panel.GetItem(1).(*tview.List)
	if list.GetItemCount() != 1 {
		t.Fatal("routine command changed")
	}
	list.GetItemSelectedFunc(0)()
	submitTableName(u, "sample")
	want := "CREATE PROCEDURE [dbo].[sample]\n    @value int\nAS\nBEGIN\n    SET NOCOUNT ON;\n    SELECT @value AS value;\nEND;"
	if tab.Editor.Area.GetText() != want {
		t.Fatal("existing routine template changed")
	}
}
