// Translate application-owned labels only. SQL, values, identifiers, host names
// and server/driver errors are intentionally never passed through this catalog.
func (u *UI) tr(text string) string {
	if u.cfg.Language != "es" {
		return text
	}
	key := strings.TrimSpace(text)
	if translated, ok := spanish[key]; ok {
		left := len(text) - len(strings.TrimLeft(text,
			" \t\n"))
		right := len(text) - len(strings.TrimRight(text,
			" \t\n"))
		return text[:left] + translated + text[len(text)-right:]
	}
	return text
}

func (u *UI) languageMenu() {
	list := tview.NewList().ShowSecondaryText(false)
	list.SetBorder(true).SetTitle(" Language / Idioma ")
	for _, item := range []struct{ id, name string }{{"en",
		"English"}, {"es",
		"Español"}} {
		choice := item
		list.AddItem(choice.name,
			"", 0, func() {
				next := u.cfg
				next.Language = choice.id
				if err := config.Save(u.configPath, next); err != nil {
					u.message(err.Error())
					return
				}
				u.cfg = next
				u.dismiss()
				u.search.SetLabel(u.tr("Find: "))
				u.kind.SetLabel(u.tr("Type: "))
				index, _ := u.kind.GetCurrentOption()
				u.kind.SetOptions(u.kindOptions(), func(string, int) { u.filterObjects() }).SetCurrentOption(index)
				u.refreshBars()
			})
	}
	u.popup(list, 50, 7)
}

