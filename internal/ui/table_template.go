package ui

import "strings"

// tableTemplate prepares editable SQL only; execution remains an explicit action.
func (u *UI) tableTemplate() {
	t := u.active()
	if t.SelectingDatabase {
		u.message(u.tr("Choose a database first (F4)"))
		return
	}
	if t.Session == nil {
		u.message(u.tr("Connect first"))
		return
	}
	a := t.Session.Adapter
	if a.Engine() == "mysql" && t.Profile.Database == "" {
		u.message(u.tr("Choose a database with Space b first"))
		return
	}
	u.prompt(u.tr("New table name (unqualified)"), "new_table", false, func(name string) {
		if strings.TrimSpace(name) == "" {
			return
		}
		schema, id, column := "public", "INTEGER GENERATED BY DEFAULT AS IDENTITY", "VARCHAR(255)"
		switch a.Engine() {
		case "sqlserver":
			schema, id, column = "dbo", "INT IDENTITY(1,1)", "NVARCHAR(255)"
		case "mysql":
			schema, id = t.Profile.Database, "INT AUTO_INCREMENT"
		}
		target := a.Quote(schema) + "." + a.Quote(name)
		text := "CREATE TABLE " + target + " (\n    id " + id + " PRIMARY KEY,\n    name " + column + " NOT NULL\n);"
		load := func() {
			t.Editor.SetText(text)
			t.Path = ""
			t.Saved = ""
			t.Object = nil
			u.refreshBars()
		}
		if t.Editor.Area.GetText() != t.Saved {
			u.confirm(u.tr("Replace unsaved SQL with template?"), load)
		} else {
			load()
		}
	})
}
