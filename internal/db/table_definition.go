package db

import (
	"context"
	"database/sql"
	"fmt"
	"strings"
)

// Los scripts de tablas sirven para inspección, no sustituyen la exportación
// del esquema. Los metadatos se leen con la conexión existente de la pestaña.
func (a *adapter) tableDefinition(ctx context.Context, c *sql.Conn, o Object) (string, error) {
	columnsQuery, constraintsQuery, indexesQuery := sqlServerTableColumns, sqlServerTableConstraints, sqlServerTableIndexes
	if a.engine == "postgres" {
		columnsQuery, constraintsQuery, indexesQuery = postgresTableColumns, postgresTableConstraints, postgresTableIndexes
	}
	columns, err := queryStrings(ctx, c, columnsQuery, o.ID)
	if err != nil {
		return "", err
	}
	if len(columns) == 0 {
		return "", fmt.Errorf("table definition unavailable: no visible columns or unsupported table kind")
	}
	constraints, err := queryStrings(ctx, c, constraintsQuery, o.ID)
	if err != nil {
		return "", err
	}
	indexes, err := queryStrings(ctx, c, indexesQuery, o.ID)
	if err != nil {
		return "", err
	}
	text := "CREATE TABLE " + a.qualified(o) + " (\n    " + strings.Join(append(columns, constraints...), ",\n    ") + "\n);"
	for _, index := range indexes {
		text += "\n" + strings.TrimSuffix(index, ";") + ";"
	}
	return text, nil
}

const postgresTableColumns = `SELECT quote_ident(a.attname)||' '||format_type(a.atttypid,a.atttypmod)||
 CASE WHEN a.attcollation<>t.typcollation AND a.attcollation<>0 THEN ' COLLATE '||quote_ident(cn.nspname)||'.'||quote_ident(co.collname) ELSE '' END||
 CASE WHEN a.attgenerated<>'' THEN ' GENERATED ALWAYS AS ('||pg_get_expr(d.adbin,d.adrelid)||') STORED'
 WHEN a.attidentity='a' THEN ' GENERATED ALWAYS AS IDENTITY'
 WHEN a.attidentity='d' THEN ' GENERATED BY DEFAULT AS IDENTITY'
 WHEN d.adbin IS NOT NULL THEN ' DEFAULT '||pg_get_expr(d.adbin,d.adrelid) ELSE '' END||
 CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE ' NULL' END
 FROM pg_attribute a JOIN pg_class r ON r.oid=a.attrelid JOIN pg_type t ON t.oid=a.atttypid
 LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
 LEFT JOIN pg_collation co ON co.oid=a.attcollation LEFT JOIN pg_namespace cn ON cn.oid=co.collnamespace
 WHERE a.attrelid=$1::oid AND a.attnum>0 AND NOT a.attisdropped AND r.relkind='r'
 AND NOT EXISTS (SELECT 1 FROM pg_inherits h WHERE h.inhrelid=r.oid OR h.inhparent=r.oid)
 ORDER BY a.attnum`

const postgresTableConstraints = `SELECT 'CONSTRAINT '||quote_ident(conname)||' '||pg_get_constraintdef(oid,true)
 FROM pg_constraint WHERE conrelid=$1::oid AND contype IN ('p','u','f','c','x') ORDER BY conname`

const postgresTableIndexes = `SELECT pg_get_indexdef(i.indexrelid)
 FROM pg_index i WHERE i.indrelid=$1::oid
 AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid=i.indexrelid AND c.conrelid=i.indrelid)
 ORDER BY i.indexrelid`

const sqlServerTableColumns = `SELECT QUOTENAME(c.name COLLATE DATABASE_DEFAULT)+CASE WHEN cc.definition COLLATE DATABASE_DEFAULT IS NOT NULL THEN ' AS '+cc.definition COLLATE DATABASE_DEFAULT+CASE WHEN cc.is_persisted=1 THEN ' PERSISTED' ELSE '' END ELSE
 ' '+CASE WHEN t.is_user_defined=1 THEN QUOTENAME(SCHEMA_NAME(t.schema_id))+'.'+QUOTENAME(t.name COLLATE DATABASE_DEFAULT) ELSE QUOTENAME(t.name COLLATE DATABASE_DEFAULT)+
 CASE WHEN t.name COLLATE DATABASE_DEFAULT IN ('varchar','char','varbinary','binary') THEN '('+CASE WHEN c.max_length=-1 THEN 'max' ELSE CONVERT(varchar(10),c.max_length) END+')'
 WHEN t.name COLLATE DATABASE_DEFAULT IN ('nvarchar','nchar') THEN '('+CASE WHEN c.max_length=-1 THEN 'max' ELSE CONVERT(varchar(10),c.max_length/2) END+')'
 WHEN t.name COLLATE DATABASE_DEFAULT IN ('decimal','numeric') THEN '('+CONVERT(varchar(10),c.precision)+','+CONVERT(varchar(10),c.scale)+')'
 WHEN t.name COLLATE DATABASE_DEFAULT IN ('time','datetime2','datetimeoffset') THEN '('+CONVERT(varchar(10),c.scale)+')' ELSE '' END END+
 CASE WHEN c.collation_name COLLATE DATABASE_DEFAULT IS NOT NULL THEN ' COLLATE '+c.collation_name COLLATE DATABASE_DEFAULT ELSE '' END+
 CASE WHEN ic.object_id IS NOT NULL THEN ' IDENTITY('+CONVERT(varchar(100),ic.seed_value)+','+CONVERT(varchar(100),ic.increment_value)+')' ELSE '' END+
 CASE WHEN c.is_nullable=1 THEN ' NULL' ELSE ' NOT NULL' END+
 CASE WHEN dc.definition COLLATE DATABASE_DEFAULT IS NOT NULL THEN ' CONSTRAINT '+QUOTENAME(dc.name COLLATE DATABASE_DEFAULT)+' DEFAULT '+dc.definition COLLATE DATABASE_DEFAULT ELSE '' END END
 FROM sys.columns c JOIN sys.types t ON t.user_type_id=c.user_type_id
 LEFT JOIN sys.computed_columns cc ON cc.object_id=c.object_id AND cc.column_id=c.column_id
 LEFT JOIN sys.identity_columns ic ON ic.object_id=c.object_id AND ic.column_id=c.column_id
 LEFT JOIN sys.default_constraints dc ON dc.object_id=c.default_object_id
 WHERE c.object_id=CONVERT(int,@p1) ORDER BY c.column_id`

// Los nombres del catálogo y las definiciones pueden tener intercalaciones
// distintas. Se normalizan antes de CASE, concatenaciones y UNION, sin cambiar datos.
// FOR XML PATH admite versiones de SQL Server anteriores a STRING_AGG;
// TYPE.value decodifica identificadores con caracteres especiales de XML.
const sqlServerTableConstraints = `SELECT definition FROM (
 SELECT k.name COLLATE DATABASE_DEFAULT AS name,'CONSTRAINT '+QUOTENAME(k.name COLLATE DATABASE_DEFAULT)+' '+CASE WHEN k.type='PK' THEN 'PRIMARY KEY' ELSE 'UNIQUE' END+
 CASE WHEN i.type=1 THEN ' CLUSTERED' ELSE ' NONCLUSTERED' END+' ('+
 STUFF((SELECT ', '+QUOTENAME(c.name COLLATE DATABASE_DEFAULT)+CASE WHEN ic.is_descending_key=1 THEN ' DESC' ELSE ' ASC' END
 FROM sys.index_columns ic JOIN sys.columns c ON c.object_id=ic.object_id AND c.column_id=ic.column_id
 WHERE ic.object_id=k.parent_object_id AND ic.index_id=k.unique_index_id AND ic.key_ordinal>0 ORDER BY ic.key_ordinal
 FOR XML PATH(''),TYPE).value('.','nvarchar(max)'),1,2,'')+')' AS definition
 FROM sys.key_constraints k JOIN sys.indexes i ON i.object_id=k.parent_object_id AND i.index_id=k.unique_index_id WHERE k.parent_object_id=CONVERT(int,@p1)
 UNION ALL SELECT c.name COLLATE DATABASE_DEFAULT,'CONSTRAINT '+QUOTENAME(c.name COLLATE DATABASE_DEFAULT)+' CHECK '+CASE WHEN c.is_not_for_replication=1 THEN 'NOT FOR REPLICATION ' ELSE '' END+c.definition COLLATE DATABASE_DEFAULT
 FROM sys.check_constraints c WHERE c.parent_object_id=CONVERT(int,@p1)
 UNION ALL SELECT f.name COLLATE DATABASE_DEFAULT,'CONSTRAINT '+QUOTENAME(f.name COLLATE DATABASE_DEFAULT)+' FOREIGN KEY ('+
 STUFF((SELECT ', '+QUOTENAME(COL_NAME(fc.parent_object_id,fc.parent_column_id)) FROM sys.foreign_key_columns fc
 WHERE fc.constraint_object_id=f.object_id ORDER BY fc.constraint_column_id FOR XML PATH(''),TYPE).value('.','nvarchar(max)'),1,2,'')+
 ') REFERENCES '+QUOTENAME(OBJECT_SCHEMA_NAME(f.referenced_object_id))+'.'+QUOTENAME(OBJECT_NAME(f.referenced_object_id))+' ('+
 STUFF((SELECT ', '+QUOTENAME(COL_NAME(fc.referenced_object_id,fc.referenced_column_id)) FROM sys.foreign_key_columns fc
 WHERE fc.constraint_object_id=f.object_id ORDER BY fc.constraint_column_id FOR XML PATH(''),TYPE).value('.','nvarchar(max)'),1,2,'')+')'+
 ' ON DELETE '+REPLACE(f.delete_referential_action_desc COLLATE DATABASE_DEFAULT,'_',' ')+' ON UPDATE '+REPLACE(f.update_referential_action_desc COLLATE DATABASE_DEFAULT,'_',' ')+
 CASE WHEN f.is_not_for_replication=1 THEN ' NOT FOR REPLICATION' ELSE '' END
 FROM sys.foreign_keys f WHERE f.parent_object_id=CONVERT(int,@p1)
 ) definitions ORDER BY name`

const sqlServerTableIndexes = `SELECT 'CREATE '+CASE WHEN i.is_unique=1 THEN 'UNIQUE ' ELSE '' END+
 CASE WHEN i.type=1 THEN 'CLUSTERED' ELSE 'NONCLUSTERED' END+' INDEX '+QUOTENAME(i.name COLLATE DATABASE_DEFAULT)+' ON '+
 QUOTENAME(OBJECT_SCHEMA_NAME(i.object_id))+'.'+QUOTENAME(OBJECT_NAME(i.object_id))+' ('+
 STUFF((SELECT ', '+QUOTENAME(c.name COLLATE DATABASE_DEFAULT)+CASE WHEN ic.is_descending_key=1 THEN ' DESC' ELSE ' ASC' END
 FROM sys.index_columns ic JOIN sys.columns c ON c.object_id=ic.object_id AND c.column_id=ic.column_id
 WHERE ic.object_id=i.object_id AND ic.index_id=i.index_id AND ic.key_ordinal>0 ORDER BY ic.key_ordinal
 FOR XML PATH(''),TYPE).value('.','nvarchar(max)'),1,2,'')+')'+
 CASE WHEN EXISTS (SELECT 1 FROM sys.index_columns ic WHERE ic.object_id=i.object_id AND ic.index_id=i.index_id AND ic.is_included_column=1)
 THEN ' INCLUDE ('+STUFF((SELECT ', '+QUOTENAME(c.name COLLATE DATABASE_DEFAULT) FROM sys.index_columns ic JOIN sys.columns c ON c.object_id=ic.object_id AND c.column_id=ic.column_id
 WHERE ic.object_id=i.object_id AND ic.index_id=i.index_id AND ic.is_included_column=1 ORDER BY ic.index_column_id
 FOR XML PATH(''),TYPE).value('.','nvarchar(max)'),1,2,'')+')' ELSE '' END+
 CASE WHEN i.has_filter=1 THEN ' WHERE '+i.filter_definition COLLATE DATABASE_DEFAULT ELSE '' END
 FROM sys.indexes i WHERE i.object_id=CONVERT(int,@p1) AND i.type IN (1,2) AND i.is_primary_key=0 AND i.is_unique_constraint=0 AND i.is_hypothetical=0 ORDER BY i.index_id`
